// გაუწერე კონფიგურაცია (Options): fetch-ის მეორე არგუმენტში მიუთითე:
// method: POST
// body: გადაეცი შენ მიერ შექმნილი FormData ობიექტი (გაითვალისწინე: ამ დროს JSON.stringify და headers არ გვჭირდება).
