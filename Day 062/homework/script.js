// 1. While Loop: "რიცხვების ჯამი"
// დავალება: დაწერე პროგრამა, რომელიც მომხმარებელს სთხოვს რიცხვების შეყვანას. პროგრამამ უნდა შეაჯამოს ეს რიცხვები მანამ, სანამ მომხმარებელი არ შეიყვანს 0-ს. როგორც კი მომხმარებელი შეიყვანს ნულს, პროგრამამ უნდა დაბეჭდოს საბოლოო ჯამი და შეწყვიტოს მუშაობა.

let sum = 0;
let number;

while (true) {
  number = Number(prompt("შეიყვანე რიცხვი (0 - გასასვლელად):"));
  
  if (number === 0) {
    break;
  }

  sum += number;
}

console.log("საბოლოო ჯამი არის:", sum);


// 2. For Loop: "გამრავლების ტაბულა"
// დავალება: მომხმარებელს შეაყვანინე ერთი კონკრეტული რიცხვი (მაგალითად, 7). პროგრამამ for ციკლის გამოყენებით უნდა დაბეჭდოს ამ რიცხვის გამრავლების ტაბულა 1-დან 10-მდე.

let num = Number(prompt("შეიყვანე რიცხვი:"));

for (let i = 1; i <= 10; i++) {
  console.log(`${num} x ${i} = ${num * i}`);
}


// 3. Do-While Loop: "პაროლის ვალიდაცია"
// დავალება: შექმენი "საიდუმლო პაროლი" (მაგ: "1234"). პროგრამამ მომხმარებელს უნდა სთხოვოს პაროლის შეყვანა. თუ პაროლი არასწორია, პროგრამამ კვლავ უნდა სთხოვოს მისი შეყვანა. do-while გამოიყენე იმისთვის, რომ კითხვა ("შეიყვანეთ პაროლი") ერთხელ მაინც დასვას და გაგრძელდეს მანამ, სანამ მომხმარებელი სწორ პასუხს არ დაწერს.

const correctPassword = "1234";
let userPassword;

do {
  userPassword = prompt("შეიყვანეთ პაროლი:");
} while (userPassword !== correctPassword);

console.log("პაროლი სწორია!");


// 4. "რიცხვების ფილტრაცია"
// დავალება: for ციკლის გამოყენებით გაიარე რიცხვები 1-დან 50-მდე.
// თუ რიცხვი იყოფა 3-ზე, დაბეჭდე "Fizz".
// თუ რიცხვი იყოფა 5-ზე, დაბეჭდე "Buzz".
// თუ იყოფა ორივეზე, დაბეჭდე "FizzBuzz".
// სხვა შემთხვევაში დაბეჭდე თავად რიცხვი.

for (let i = 1; i <= 50; i++) {
  if (i % 3 === 0 && i % 5 === 0) {
    console.log("FizzBuzz");
  } else if (i % 3 === 0) {
    console.log("Fizz");
  } else if (i % 5 === 0) {
    console.log("Buzz");
  } else {
    console.log(i);
  }
}